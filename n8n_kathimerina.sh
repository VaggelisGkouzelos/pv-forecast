#!/bin/bash
# ============================================================
# ΟΛΟ ΤΟ ΚΑΘΗΜΕΡΙΝΟ PIPELINE. Το τρέχει το n8n κάθε πρωί.
#
#   02 -> ενώνει ΟΛΑ τα Excel (και τα καινούργια) με τον καιρό
#   03 -> βρίσκει περικοπές/βλάβες και ξαναεκπαιδεύει το μοντέλο
#   04 -> πρόβλεψη για αύριο/μεθαύριο
#   05 -> γράφει τη σύντομη αναφορά
#
# Τα 02-04 γράφουν πολλά "τεχνικά" μηνύματα -> τα κρατάμε σε αρχείο (logs/).
# Στην οθόνη (άρα και στο n8n) βγαίνει ΜΟΝΟ η τελική αναφορά του 05.
# ============================================================
cd "$(dirname "$0")"
source .venv/bin/activate
export MPLBACKEND=Agg                      # χωρίς παράθυρα γραφημάτων
mkdir -p logs
LOG="logs/$(date +%Y-%m-%d).log"           # ένα αρχείο log για κάθε μέρα

# "set -e": αν κάποιο βήμα αποτύχει, σταματάμε (και το n8n θα δείξει κόκκινο)
set -e
python3 02_ekpaideusi.py  >  "$LOG" 2>&1
python3 03_katharismos.py >> "$LOG" 2>&1
python3 04_provlepsi.py   >> "$LOG" 2>&1
python3 05_anafora.py
